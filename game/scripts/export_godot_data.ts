// Exports every plain-data constant the TypeScript game defines (units,
// buildings, techs, factions, balance numbers, map presets, AI tiers…) to
// JSON for the Godot port, so both versions read exactly the same numbers.
//
//   npx tsx scripts/export_godot_data.ts
//
// Functions inside the data (an Oath's `apply`, a boon's `lines`) can't travel
// as JSON; they're listed in the output's `_functions` so the Godot side can
// check it ported each one by hand.

import fs from "fs";
import path from "path";

const MODULES = [
  "content/balance", "content/units", "content/buildings", "content/tech", "content/factions",
  "content/oaths", "content/boons", "content/commanders", "content/abilities", "content/battle_styles",
  "content/daynight", "ai/difficulty", "maps/terrain_kinds", "maps/generator", "maps/symmetry", "maps/custom", "maps/script", "render/palette", "meta/rarity",
  "meta/catalog", "meta/keybinds", "meta/chests", "meta/progression", "meta/achievements", "sim/unit_tiers",
  "sim/warband_commanders", "sim/warband_difficulty", "sim/traits", "sim/augments", "sim/items",
  "meta/boon_cache", "meta/profile", "meta/settings", "meta/history", "meta/career", "meta/playstyle", "meta/rival",
];

const out: Record<string, Record<string, unknown>> = {};
const fns: string[] = [];

function clean(v: unknown, where: string, seen = new Set<unknown>()): unknown {
  if (typeof v === "function") { fns.push(where); return undefined; }
  if (v === null || typeof v !== "object") return typeof v === "number" && !Number.isFinite(v) ? (v > 0 ? 1e308 : -1e308) : v;
  if (seen.has(v)) return undefined;
  seen.add(v);
  if (v instanceof Set) return [...v].map((x, i) => clean(x, `${where}[${i}]`, seen));
  if (v instanceof Map) return Object.fromEntries([...v].map(([k, x]) => [k, clean(x, `${where}.${k}`, seen)]));
  if (Array.isArray(v)) return v.map((x, i) => clean(x, `${where}[${i}]`, seen));
  const o: Record<string, unknown> = {};
  for (const [k, x] of Object.entries(v)) { const c = clean(x, `${where}.${k}`, seen); if (c !== undefined) o[k] = c; }
  seen.delete(v);
  return o;
}

for (const m of MODULES) {
  const mod = await import(path.resolve("src", m + ".ts"));
  const entries: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(mod)) {
    if (typeof v === "function") continue; // exported helpers are ported as code
    const c = clean(v, `${m}.${k}`);
    if (c !== undefined) entries[k] = c;
  }
  out[m] = entries;
}
(out as any)._functions = fns;
const dest = path.resolve("../godot/data/content.json");
const text = JSON.stringify(out);
fs.writeFileSync(dest, text);
// Godot's text-to-float isn't correctly rounded for every literal (it reads
// 0.9797282677609473 one ulp off), so the exact bits of every number travel
// alongside in document order and the loader patches them in.
const nums: number[] = [];
(function walk(v: unknown) {
  if (typeof v === "number") nums.push(v);
  else if (Array.isArray(v)) v.forEach(walk);
  else if (v && typeof v === "object") for (const k of Object.keys(v)) walk((v as Record<string, unknown>)[k]);
})(JSON.parse(text));
fs.writeFileSync(path.resolve("../godot/data/content.f64"), Buffer.from(new Float64Array(nums).buffer));
// The Godot autoload `C`: one variable per exported constant, named exactly as
// in TypeScript, filled from the JSON at startup. `C.UNITS`, `C.TILE`, ...
const seenNames = new Map<string, string>();
const lines: string[] = [];
for (const [m, entries] of Object.entries(out)) {
  if (m === "_functions") continue;
  for (const [k, v] of Object.entries(entries as Record<string, unknown>)) {
    if (seenNames.has(k)) { console.warn(`name clash: ${k} in ${m} and ${seenNames.get(k)} — reach it as C.mod("${m}").${k}`); continue; }
    seenNames.set(k, m);
    const ty = typeof v === "number" ? "float" : typeof v === "string" ? "String" : typeof v === "boolean" ? "bool" : Array.isArray(v) ? "Array" : "Dictionary";
    lines.push(`var ${k}: ${ty}  # ${m}`);
  }
}
const gd = `## Generated by game/scripts/export_godot_data.ts — do not edit by hand.
##
## Every plain-data constant the TypeScript game exports, under the same name:
## C.UNITS, C.BUILDINGS, C.TILE, C.SIM_HZ, ... loaded from data/content.json so
## both builds read exactly the same numbers. JSON numbers are floats (as in
## JS); cast with int() where an integer is needed.
extends Node

var modules: Dictionary = {}
${lines.join("\n")}


func _init() -> void:
	var f := FileAccess.open("res://data/content.json", FileAccess.READ)
	var data: Dictionary = JSON.parse_string(f.get_as_text())
	# Patch in the exact bits of every number (see the exporter).
	var bits := FileAccess.get_file_as_bytes("res://data/content.f64")
	var nums := bits.to_float64_array()
	var cursor := [0]
	_patch(data, nums, cursor)
	modules = data
	for m in data:
		if m == "_functions":
			continue
		for k in data[m]:
			if k in self:
				set(k, data[m][k])


func _patch(v, nums: PackedFloat64Array, cursor: Array):
	if v is Dictionary:
		for k in v:
			if v[k] is float:
				v[k] = nums[cursor[0]]
				cursor[0] += 1
			elif v[k] is Dictionary or v[k] is Array:
				_patch(v[k], nums, cursor)
	elif v is Array:
		for i in v.size():
			if v[i] is float:
				v[i] = nums[cursor[0]]
				cursor[0] += 1
			elif v[i] is Dictionary or v[i] is Array:
				_patch(v[i], nums, cursor)


## Everything one TS module exports, by its path ("content/units").
func mod(path: String) -> Dictionary:
	return modules.get(path, {})
`;
fs.writeFileSync(path.resolve("../godot/src/autoload/c.gd"), gd);
console.log(`wrote ${dest}: ${Object.keys(out).length - 1} modules, ${(fs.statSync(dest).size / 1024).toFixed(0)} KB, ${fns.length} functions to port by hand`);
